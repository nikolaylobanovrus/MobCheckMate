"""Convert SVG files to Android VectorDrawable XML, applying all transforms.

Used for the Cburnett piece set (Wikimedia Commons, BSD licence) and Material Symbols icons (Apache 2.0); see
docs/THIRD_PARTY_NOTICES.md. Needs `pip install svgelements`.

    python3 tools/svg_to_vector.py piece input.svg output.xml   # 45x45 piece: fills, strokes, transforms
    python3 tools/svg_to_vector.py icon input.svg output.xml    # Material Symbol: one black shape, tinted in the app

Shapes (paths, circles, ellipses, lines, polygons, rects) are turned into path data with their transforms
applied, so the drawable needs no groups. Stroke widths are scaled by the transform's scale factor; the pieces
only use translations and rotations, which keep widths unchanged.
"""
import math
import sys

from svgelements import SVG, Shape, Path, Color

HEADER = {
    "piece": "<!-- Cburnett chess pieces, Wikimedia Commons, BSD licence (see docs/THIRD_PARTY_NOTICES.md). "
             "Generated by tools/svg_to_vector.py. -->",
    "icon": "<!-- Material Symbols Rounded, Google, Apache 2.0. Generated by tools/svg_to_vector.py. -->",
}


def fmt(x: float) -> str:
    return ("%.3f" % x).rstrip("0").rstrip(".") or "0"


def color(c) -> str | None:
    if c is None or c.value is None:
        return None
    c = Color(c)
    if c.alpha == 0:
        return None
    return "#%02X%02X%02X%02X" % (c.alpha, c.red, c.green, c.blue)


def path_data(shape: Shape) -> str:
    path = abs(Path(shape))  # abs() applies the transform
    return path.d()


def convert(kind: str, source: str, target: str) -> None:
    svg = SVG.parse(source, reify=True)
    if kind == "icon":
        # Material Symbols use viewBox "0 -960 960 960"; svgelements maps it to the 24x24 size.
        width = height = 24.0
    else:
        width, height = float(svg.width), float(svg.height)
    paths = []
    for element in svg.elements():
        if not isinstance(element, Shape) or isinstance(element, SVG):
            continue
        d = path_data(element)
        if not d:
            continue
        attrs = [f'android:pathData="{d}"']
        if kind == "icon":
            attrs.append('android:fillColor="#FF000000"')
        else:
            fill = color(element.fill)
            stroke = color(element.stroke)
            if fill:
                attrs.append(f'android:fillColor="{fill}"')
            if element.values.get("fill-rule") == "evenodd":
                attrs.append('android:fillType="evenOdd"')
            if stroke:
                scale = math.sqrt(abs(element.transform.determinant)) if element.transform else 1.0
                width_value = float(element.stroke_width or 1.0) * scale
                attrs.append(f'android:strokeColor="{stroke}"')
                attrs.append(f'android:strokeWidth="{fmt(width_value)}"')
                cap = element.values.get("stroke-linecap")
                join = element.values.get("stroke-linejoin")
                if cap in ("round", "square", "butt"):
                    attrs.append(f'android:strokeLineCap="{cap}"')
                if join in ("round", "bevel", "miter"):
                    attrs.append(f'android:strokeLineJoin="{join}"')
            if not fill and not stroke:
                continue
        paths.append("    <path\n        " + "\n        ".join(attrs) + " />")
    size = "24dp" if kind == "icon" else "45dp"
    xml = (
        f"{HEADER[kind]}\n"
        f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{size}"\n    android:height="{size}"\n'
        f'    android:viewportWidth="{fmt(width)}"\n    android:viewportHeight="{fmt(height)}">\n'
        + "\n".join(paths)
        + "\n</vector>\n"
    )
    with open(target, "w", encoding="utf-8") as f:
        f.write(xml)


if __name__ == "__main__":
    if len(sys.argv) != 4 or sys.argv[1] not in HEADER:
        sys.exit(__doc__)
    convert(sys.argv[1], sys.argv[2], sys.argv[3])
